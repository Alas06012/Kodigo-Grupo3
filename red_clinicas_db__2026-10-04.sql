-- ---------------------------------------------------------------------------
-- 4.3 DISTRIBUCION_COBRO (Responsabilidad Desglosada con Saldos por Entidad)
-- ---------------------------------------------------------------------------
CREATE TABLE DISTRIBUCION_COBRO (
    ID_DISTRIBUCION           NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ID_COBRO                  NUMBER        NOT NULL,
    TIPO_PAGADOR              VARCHAR2(15)  NOT NULL,
    ID_PACIENTE               NUMBER,
    ID_ASEGURADORA            NUMBER,
    ID_EMPRESA                NUMBER,
    PORCENTAJE                NUMBER(5,2)   NOT NULL,
    MONTO_ASIGNADO            NUMBER(10,2)  NOT NULL,
    MONTO_PAGADO              NUMBER(10,2)  DEFAULT 0 NOT NULL,
    SALDO_PENDIENTE           NUMBER(10,2)  GENERATED ALWAYS AS (MONTO_ASIGNADO - MONTO_PAGADO) VIRTUAL,
    ESTADO                    VARCHAR2(15)  DEFAULT 'PENDIENTE' NOT NULL,
    CONSTRAINT PK_DISTRIBUCION_COBRO  PRIMARY KEY (ID_DISTRIBUCION),
    CONSTRAINT FK_DISTCOB_COBRO       FOREIGN KEY (ID_COBRO) REFERENCES COBROS_CONSULTA (ID_COBRO),
    CONSTRAINT FK_DISTCOB_PACIENTE    FOREIGN KEY (ID_PACIENTE) REFERENCES PACIENTES (ID_PACIENTE),
    CONSTRAINT FK_DISTCOB_ASEGURADORA FOREIGN KEY (ID_ASEGURADORA) REFERENCES ASEGURADORAS (ID_ASEGURADORA),
    CONSTRAINT FK_DISTCOB_EMPRESA     FOREIGN KEY (ID_EMPRESA) REFERENCES EMPRESAS (ID_EMPRESA),
    CONSTRAINT CK_DISTCOB_TIPO        CHECK (TIPO_PAGADOR IN ('PACIENTE','ASEGURADORA','EMPRESA')),
    CONSTRAINT CK_DISTCOB_PORCENTAJE  CHECK (PORCENTAJE > 0 AND PORCENTAJE <= 100),
    CONSTRAINT CK_DISTCOB_MONTO       CHECK (MONTO_ASIGNADO >= 0 AND MONTO_PAGADO >= 0),
    CONSTRAINT CK_DISTCOB_ESTADO      CHECK (ESTADO IN ('PENDIENTE','PARCIAL','PAGADO')),
    CONSTRAINT CK_DISTCOB_COHERENCIA  CHECK (
        (TIPO_PAGADOR = 'PACIENTE'    AND ID_PACIENTE IS NOT NULL AND ID_ASEGURADORA IS NULL AND ID_EMPRESA IS NULL) OR
        (TIPO_PAGADOR = 'ASEGURADORA' AND ID_ASEGURADORA IS NOT NULL AND ID_PACIENTE IS NULL AND ID_EMPRESA IS NULL) OR
        (TIPO_PAGADOR = 'EMPRESA'     AND ID_EMPRESA IS NOT NULL AND ID_PACIENTE IS NULL AND ID_ASEGURADORA IS NULL)
    )
);

COMMENT ON TABLE  DISTRIBUCION_COBRO IS 'Reparto de responsabilidad económica y control individual de saldos';
COMMENT ON COLUMN DISTRIBUCION_COBRO.SALDO_PENDIENTE IS 'Deuda pendiente de cobro específica de ese pagador';


