CREATE TABLE STG_DIAGNOSTICOS (
    ID_DIAGNOSTICO         NUMBER NOT NULL,
    ID_CONSULTA            NUMBER NOT NULL,
    ID_ENFERMEDAD          NUMBER NOT NULL,
    FECHA_DIAGNOSTICO      DATE NOT NULL,
    OBSERVACIONES          VARCHAR2(300),
    -- 6 Columnas Técnicas de Auditoría
    CURRENTFLAG            NUMBER(1)    DEFAULT 1 NOT NULL,
    TIPOCARGA              VARCHAR2(20) DEFAULT 'FULL' NOT NULL,
    FECHAINICIO            DATE         DEFAULT SYSDATE NOT NULL,
    FECHAFIN              DATE         DEFAULT DATE '2999-12-31' NOT NULL,
    TIPOTRANSACCION        CHAR(1)      DEFAULT 'I' NOT NULL,
    ROWHASHVALUE           VARCHAR2(64) NOT NULL,
    CONSTRAINT CK_STG_DIA_FLAG   CHECK (CURRENTFLAG IN (0, 1)),
    CONSTRAINT CK_STG_DIA_CARGA  CHECK (TIPOCARGA IN ('FULL', 'INCREMENTAL')),
    CONSTRAINT CK_STG_DIA_TRX    CHECK (TIPOTRANSACCION IN ('I', 'U', 'D'))
);

CREATE INDEX IX_STG_DIA_ID ON STG_DIAGNOSTICOS (ID_DIAGNOSTICO);
CREATE INDEX IX_STG_DIA_CONS ON STG_DIAGNOSTICOS (ID_CONSULTA);
COMMENT ON TABLE STG_DIAGNOSTICOS IS 'Staging: Diagnósticos asociados a las consultas';

