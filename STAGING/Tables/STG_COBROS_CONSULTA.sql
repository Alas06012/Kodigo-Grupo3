CREATE TABLE STG_COBROS_CONSULTA (
    ID_COBRO               NUMBER NOT NULL,
    ID_CONSULTA            NUMBER NOT NULL,
    MONTO_TOTAL_FACTURADO  NUMBER(10,2) NOT NULL,
    MONTO_TOTAL_PAGADO     NUMBER(10,2) NOT NULL,
    SALDO_PENDIENTE        NUMBER(10,2) NOT NULL,
    ESTADO_COBRO           VARCHAR2(15) NOT NULL,
    FECHA_EMISION          DATE NOT NULL,
    -- 6 Columnas Técnicas de Auditoría
    CURRENTFLAG            NUMBER(1)    DEFAULT 1 NOT NULL,
    TIPOCARGA              VARCHAR2(20) DEFAULT 'FULL' NOT NULL,
    FECHAINICIO            DATE         DEFAULT SYSDATE NOT NULL,
    FECHAFIN              DATE         DEFAULT DATE '2999-12-31' NOT NULL,
    TIPOTRANSACCION        CHAR(1)      DEFAULT 'I' NOT NULL,
    ROWHASHVALUE           VARCHAR2(64) NOT NULL,
    CONSTRAINT CK_STG_COB_FLAG   CHECK (CURRENTFLAG IN (0, 1)),
    CONSTRAINT CK_STG_COB_CARGA  CHECK (TIPOCARGA IN ('FULL', 'INCREMENTAL')),
    CONSTRAINT CK_STG_COB_TRX    CHECK (TIPOTRANSACCION IN ('I', 'U', 'D'))
);

CREATE INDEX IX_STG_COB_ID ON STG_COBROS_CONSULTA (ID_COBRO);
CREATE INDEX IX_STG_COB_CONS ON STG_COBROS_CONSULTA (ID_CONSULTA);
CREATE INDEX IX_STG_COB_FECHA ON STG_COBROS_CONSULTA (FECHA_EMISION);
COMMENT ON TABLE STG_COBROS_CONSULTA IS 'Staging: Cuenta global consolidada de la atención médica';

