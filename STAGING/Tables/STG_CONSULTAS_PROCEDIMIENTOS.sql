CREATE TABLE STG_CONSULTAS_PROCEDIMIENTOS (
    ID_CONSULTA_PROCEDIMIENTO NUMBER NOT NULL,
    ID_CONSULTA               NUMBER NOT NULL,
    ID_PROCEDIMIENTO          NUMBER NOT NULL,
    CANTIDAD                  NUMBER(3) NOT NULL,
    PRECIO_UNITARIO           NUMBER(10,2) NOT NULL,
    SUBTOTAL                  NUMBER(10,2) NOT NULL,
    OBSERVACIONES             VARCHAR2(300),
    FECHA_REALIZACION         DATE NOT NULL,
    -- 6 Columnas Técnicas de Auditoría
    CURRENTFLAG               NUMBER(1)    DEFAULT 1 NOT NULL,
    TIPOCARGA                 VARCHAR2(20) DEFAULT 'FULL' NOT NULL,
    FECHAINICIO               DATE         DEFAULT SYSDATE NOT NULL,
    FECHAFIN                  DATE         DEFAULT DATE '2999-12-31' NOT NULL,
    TIPOTRANSACCION           CHAR(1)      DEFAULT 'I' NOT NULL,
    ROWHASHVALUE              VARCHAR2(64) NOT NULL,
    CONSTRAINT CK_STG_CPR_FLAG   CHECK (CURRENTFLAG IN (0, 1)),
    CONSTRAINT CK_STG_CPR_CARGA  CHECK (TIPOCARGA IN ('FULL', 'INCREMENTAL')),
    CONSTRAINT CK_STG_CPR_TRX    CHECK (TIPOTRANSACCION IN ('I', 'U', 'D'))
);

CREATE INDEX IX_STG_CPR_ID ON STG_CONSULTAS_PROCEDIMIENTOS (ID_CONSULTA_PROCEDIMIENTO);
CREATE INDEX IX_STG_CPR_CONS ON STG_CONSULTAS_PROCEDIMIENTOS (ID_CONSULTA);
COMMENT ON TABLE STG_CONSULTAS_PROCEDIMIENTOS IS 'Staging: Detalle de procedimientos realizados en consulta';

