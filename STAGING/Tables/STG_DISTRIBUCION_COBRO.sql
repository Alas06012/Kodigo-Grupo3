CREATE TABLE STG_DISTRIBUCION_COBRO (
    ID_DISTRIBUCION        NUMBER NOT NULL,
    ID_COBRO               NUMBER NOT NULL,
    TIPO_PAGADOR           VARCHAR2(15) NOT NULL,
    ID_PACIENTE            NUMBER,
    ID_ASEGURADORA         NUMBER,
    ID_EMPRESA             NUMBER,
    PORCENTAJE             NUMBER(5,2) NOT NULL,
    MONTO_ASIGNADO         NUMBER(10,2) NOT NULL,
    MONTO_PAGADO           NUMBER(10,2) NOT NULL,
    SALDO_PENDIENTE        NUMBER(10,2) NOT NULL,
    ESTADO                 VARCHAR2(15) NOT NULL,
    -- 6 Columnas Técnicas de Auditoría
    CURRENTFLAG            NUMBER(1)    DEFAULT 1 NOT NULL,
    TIPOCARGA              VARCHAR2(20) DEFAULT 'FULL' NOT NULL,
    FECHAINICIO            DATE         DEFAULT SYSDATE NOT NULL,
    FECHAFIN              DATE         DEFAULT DATE '2999-12-31' NOT NULL,
    TIPOTRANSACCION        CHAR(1)      DEFAULT 'I' NOT NULL,
    ROWHASHVALUE           VARCHAR2(64) NOT NULL,
    CONSTRAINT CK_STG_DIS_FLAG   CHECK (CURRENTFLAG IN (0, 1)),
    CONSTRAINT CK_STG_DIS_CARGA  CHECK (TIPOCARGA IN ('FULL', 'INCREMENTAL')),
    CONSTRAINT CK_STG_DIS_TRX    CHECK (TIPOTRANSACCION IN ('I', 'U', 'D'))
);

CREATE INDEX IX_STG_DIS_ID ON STG_DISTRIBUCION_COBRO (ID_DISTRIBUCION);
CREATE INDEX IX_STG_DIS_COB ON STG_DISTRIBUCION_COBRO (ID_COBRO);
COMMENT ON TABLE STG_DISTRIBUCION_COBRO IS 'Staging: Responsabilidad económica desglosada por pagador';

