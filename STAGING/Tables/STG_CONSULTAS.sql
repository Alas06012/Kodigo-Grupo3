CREATE TABLE STG_CONSULTAS (
    ID_CONSULTA            NUMBER NOT NULL,
    ID_PACIENTE            NUMBER NOT NULL,
    ID_CLINICA             NUMBER NOT NULL,
    ID_MEDICO              NUMBER NOT NULL,
    ID_ESPECIALIDAD        NUMBER NOT NULL,
    ID_TIPO_CONSULTA       NUMBER NOT NULL,
    FECHA_CONSULTA         DATE NOT NULL,
    PRECIO_CONSULTA        NUMBER(10,2) NOT NULL,
    MOTIVO_CONSULTA        VARCHAR2(400),
    PRESCRIPCION           VARCHAR2(4000),
    -- 6 Columnas Técnicas de Auditoría
    CURRENTFLAG            NUMBER(1)    DEFAULT 1 NOT NULL,
    TIPOCARGA              VARCHAR2(20) DEFAULT 'FULL' NOT NULL,
    FECHAINICIO            DATE         DEFAULT SYSDATE NOT NULL,
    FECHAFIN              DATE         DEFAULT DATE '2999-12-31' NOT NULL,
    TIPOTRANSACCION        CHAR(1)      DEFAULT 'I' NOT NULL,
    ROWHASHVALUE           VARCHAR2(64) NOT NULL,
    CONSTRAINT CK_STG_CON_FLAG   CHECK (CURRENTFLAG IN (0, 1)),
    CONSTRAINT CK_STG_CON_CARGA  CHECK (TIPOCARGA IN ('FULL', 'INCREMENTAL')),
    CONSTRAINT CK_STG_CON_TRX    CHECK (TIPOTRANSACCION IN ('I', 'U', 'D'))
);

CREATE INDEX IX_STG_CON_ID ON STG_CONSULTAS (ID_CONSULTA);
CREATE INDEX IX_STG_CON_FECHA ON STG_CONSULTAS (FECHA_CONSULTA);
COMMENT ON TABLE STG_CONSULTAS IS 'Staging: Registro de actos médicos efectuados';

