CREATE TABLE STG_TRANSACCIONES_PAGO (
    ID_TRANSACCION         NUMBER NOT NULL,
    ID_COBRO               NUMBER NOT NULL,
    ID_DISTRIBUCION        NUMBER NOT NULL,
    ID_FORMA_PAGO          NUMBER NOT NULL,
    MONTO_TRANSACCION      NUMBER(10,2) NOT NULL,
    FECHA_PAGO             DATE NOT NULL,
    NUMERO_REFERENCIA      VARCHAR2(50),
    OBSERVACIONES          VARCHAR2(250),
    -- 6 Columnas Técnicas de Auditoría
    CURRENTFLAG            NUMBER(1)    DEFAULT 1 NOT NULL,
    TIPOCARGA              VARCHAR2(20) DEFAULT 'FULL' NOT NULL,
    FECHAINICIO            DATE         DEFAULT SYSDATE NOT NULL,
    FECHAFIN              DATE         DEFAULT DATE '2999-12-31' NOT NULL,
    TIPOTRANSACCION        CHAR(1)      DEFAULT 'I' NOT NULL,
    ROWHASHVALUE           VARCHAR2(64) NOT NULL,
    CONSTRAINT CK_STG_TRX_FLAG   CHECK (CURRENTFLAG IN (0, 1)),
    CONSTRAINT CK_STG_TRX_CARGA  CHECK (TIPOCARGA IN ('FULL', 'INCREMENTAL')),
    CONSTRAINT CK_STG_TRX_TRX    CHECK (TIPOTRANSACCION IN ('I', 'U', 'D'))
);

CREATE INDEX IX_STG_TRX_ID ON STG_TRANSACCIONES_PAGO (ID_TRANSACCION);
CREATE INDEX IX_STG_TRX_FECHA ON STG_TRANSACCIONES_PAGO (FECHA_PAGO);
COMMENT ON TABLE STG_TRANSACCIONES_PAGO IS 'Staging: Libro diario de abonos e ingresos reales';
