/* ============================================================================
   PROYECTO DATA WAREHOUSE - RED DE CLÍNICAS
   CAPA STAGING: CREACIÓN INTEGRAL DE LAS 18 TABLAS DE ATERRIZAJE (LANDING)
   MOTOR: Oracle Database 19c / 21c / 23ai (XEPDB1)
   ESQUEMA: stg_clinica_user | TABLESPACE: stg_clinicas_db
   ============================================================================
   INSTRUCCIONES DE EJECUCIÓN:
     - Conectarse en SQL Developer, DBeaver, VS Code o SQL*Plus como: stg_clinica_user
     - Este script es idempotente: elimina tablas previas de Staging de forma segura
       y recrea las 18 estructuras en orden con sus columnas técnicas y permisos.
   ============================================================================ */

SET FEEDBACK ON;
SET ECHO OFF;

-- ============================================================================
-- 0. LIMPIEZA PREVIA DE TABLAS DE STAGING
-- ============================================================================
BEGIN
    FOR t IN (
        SELECT table_name 
        FROM user_tables 
        WHERE table_name IN (
            'STG_UBICACIONES', 'STG_EMPRESAS', 'STG_ASEGURADORAS', 'STG_ESPECIALIDADES',
            'STG_ENFERMEDADES', 'STG_TIPOS_CONSULTA', 'STG_PROCEDIMIENTOS', 'STG_FORMAS_PAGO',
            'STG_CLINICAS', 'STG_MEDICOS', 'STG_PACIENTES', 'STG_MEDICOS_ESPECIALIDADES',
            'STG_CONSULTAS', 'STG_DIAGNOSTICOS', 'STG_CONSULTAS_PROCEDIMIENTOS',
            'STG_COBROS_CONSULTA', 'STG_DISTRIBUCION_COBRO', 'STG_TRANSACCIONES_PAGO'
        )
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

