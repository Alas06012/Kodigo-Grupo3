    LEFT JOIN stg_clinica_user.STG_CLINICAS c     ON p.ID_CLINICA_HABITUAL = c.ID_CLINICA
    LEFT JOIN stg_clinica_user.STG_EMPRESAS e     ON p.ID_EMPRESA = e.ID_EMPRESA
