-- ============================================================================
-- 0. LIMPIEZA PREVIA ORDENADA (HIJAS -> PADRES)
-- ============================================================================
BEGIN
    FOR t IN (
        SELECT table_name FROM user_tables WHERE table_name IN (
            'TRANSACCIONES_PAGO', 'DISTRIBUCION_COBRO', 'COBROS_CONSULTA',
            'CONSULTAS_PROCEDIMIENTOS', 'DIAGNOSTICOS', 'CONSULTAS',
            'MEDICOS_ESPECIALIDADES', 'PACIENTES', 'MEDICOS', 'CLINICAS',
            'FORMAS_PAGO', 'PROCEDIMIENTOS', 'TIPOS_CONSULTA', 'ENFERMEDADES',
            'ESPECIALIDADES', 'ASEGURADORAS', 'EMPRESAS', 'UBICACIONES'
        )
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
