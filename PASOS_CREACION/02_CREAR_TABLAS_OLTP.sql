-- ============================================================================
-- 1. CATÁLOGOS BASE Y MAESTROS (NIVEL 0 - SIN DEPENDENCIAS FK)
-- ============================================================================

-- 1.1 UBICACIONES
CREATE TABLE UBICACIONES (
    ID_UBICACION          NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    PAIS                  VARCHAR2(60)   DEFAULT 'El Salvador' NOT NULL,
    DEPARTAMENTO          VARCHAR2(60)   NOT NULL,
    MUNICIPIO             VARCHAR2(60)   NOT NULL,
    DISTRITO              VARCHAR2(60)   NOT NULL,
    CODIGO_POSTAL         VARCHAR2(10),
    CONSTRAINT PK_UBICACIONES PRIMARY KEY (ID_UBICACION),
    CONSTRAINT UQ_UBICACIONES UNIQUE (PAIS, DEPARTAMENTO, MUNICIPIO, DISTRITO)
);
COMMENT ON TABLE  UBICACIONES IS 'Catálogo territorial para normalización de direcciones físicas';

-- 1.2 EMPRESAS
CREATE TABLE EMPRESAS (
    ID_EMPRESA             NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    NOMBRE_EMPRESA         VARCHAR2(120)  NOT NULL,
    NIT                    VARCHAR2(20)   NOT NULL,
    SECTOR                 VARCHAR2(60),
    TELEFONO               VARCHAR2(20),
    DIRECCION              VARCHAR2(200),
    CONSTRAINT PK_EMPRESAS      PRIMARY KEY (ID_EMPRESA),
    CONSTRAINT UQ_EMPRESAS_NIT  UNIQUE (NIT)
);
COMMENT ON TABLE EMPRESAS IS 'Empresas afiliadas con convenios de salud laboral';

-- 1.3 ASEGURADORAS
CREATE TABLE ASEGURADORAS (
    ID_ASEGURADORA          NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    NOMBRE_ASEGURADORA      VARCHAR2(120)  NOT NULL,
    NIT                     VARCHAR2(20)   NOT NULL,
    TIPO_COBERTURA          VARCHAR2(60),
    TELEFONO                VARCHAR2(20),
    CONSTRAINT PK_ASEGURADORAS     PRIMARY KEY (ID_ASEGURADORA),
    CONSTRAINT UQ_ASEGURADORAS_NIT UNIQUE (NIT)
);
COMMENT ON TABLE ASEGURADORAS IS 'Compañías aseguradoras que cubren pólizas de pacientes';

-- 1.4 ESPECIALIDADES
CREATE TABLE ESPECIALIDADES (
    ID_ESPECIALIDAD        NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    NOMBRE_ESPECIALIDAD    VARCHAR2(80)   NOT NULL,
    DESCRIPCION            VARCHAR2(300),
    CONSTRAINT PK_ESPECIALIDADES        PRIMARY KEY (ID_ESPECIALIDAD),
    CONSTRAINT UQ_ESPECIALIDADES_NOMBRE UNIQUE (NOMBRE_ESPECIALIDAD)
);
COMMENT ON TABLE ESPECIALIDADES IS 'Catálogo maestro de especialidades médicas';

-- 1.5 ENFERMEDADES
CREATE TABLE ENFERMEDADES (
    ID_ENFERMEDAD          NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    CODIGO_CIE10           VARCHAR2(10),
    NOMBRE_ENFERMEDAD      VARCHAR2(120)  NOT NULL,
    CONSTRAINT PK_ENFERMEDADES PRIMARY KEY (ID_ENFERMEDAD)
);
COMMENT ON TABLE ENFERMEDADES IS 'Catálogo nosológico internacional de enfermedades (CIE-10)';

-- 1.6 TIPOS_CONSULTA
CREATE TABLE TIPOS_CONSULTA (
    ID_TIPO_CONSULTA       NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    NOMBRE_TIPO            VARCHAR2(60)   NOT NULL,
    DESCRIPCION            VARCHAR2(250),
    PRECIO_BASE            NUMBER(10,2)   DEFAULT 0 NOT NULL,
    ESTADO                 VARCHAR2(10)   DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_TIPOS_CONSULTA        PRIMARY KEY (ID_TIPO_CONSULTA),
    CONSTRAINT UQ_TIPOS_CONSULTA_NOMBRE UNIQUE (NOMBRE_TIPO),
    CONSTRAINT CK_TIPOS_CONSULTA_PRECIO CHECK (PRECIO_BASE >= 0),
    CONSTRAINT CK_TIPOS_CONSULTA_ESTADO CHECK (ESTADO IN ('ACTIVO','INACTIVO'))
);
COMMENT ON TABLE TIPOS_CONSULTA IS 'Catálogo de modalidades de consulta con tarifa base sugerida';

-- 1.7 PROCEDIMIENTOS
CREATE TABLE PROCEDIMIENTOS (
    ID_PROCEDIMIENTO       NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    CODIGO_PROCEDIMIENTO   VARCHAR2(20),
    NOMBRE_PROCEDIMIENTO   VARCHAR2(120)  NOT NULL,
    DESCRIPCION            VARCHAR2(300),
    COSTO_BASE             NUMBER(10,2)   DEFAULT 0 NOT NULL,
    ESTADO                 VARCHAR2(10)   DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_PROCEDIMIENTOS        PRIMARY KEY (ID_PROCEDIMIENTO),
    CONSTRAINT UQ_PROCEDIMIENTOS_COD    UNIQUE (CODIGO_PROCEDIMIENTO),
    CONSTRAINT CK_PROCEDIMIENTOS_COSTO  CHECK (COSTO_BASE >= 0),
    CONSTRAINT CK_PROCEDIMIENTOS_ESTADO CHECK (ESTADO IN ('ACTIVO','INACTIVO'))
);
COMMENT ON TABLE PROCEDIMIENTOS IS 'Catálogo de intervenciones, terapias y procedimientos clínicos';

-- 1.8 FORMAS_PAGO
CREATE TABLE FORMAS_PAGO (
    ID_FORMA_PAGO          NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    NOMBRE_FORMA_PAGO      VARCHAR2(50)  NOT NULL,
    CATEGORIA              VARCHAR2(20)  NOT NULL,
    ESTADO                 VARCHAR2(10)  DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_FORMAS_PAGO         PRIMARY KEY (ID_FORMA_PAGO),
    CONSTRAINT UQ_FORMAS_PAGO_NOMBRE  UNIQUE (NOMBRE_FORMA_PAGO),
    CONSTRAINT CK_FORMAS_PAGO_CAT     CHECK (CATEGORIA IN ('CONTADO','CREDITO')),
    CONSTRAINT CK_FORMAS_PAGO_ESTADO  CHECK (ESTADO IN ('ACTIVO','INACTIVO'))
);
COMMENT ON TABLE FORMAS_PAGO IS 'Catálogo de medios de pago (Efectivo, Tarjeta, Transferencia)';

-- ============================================================================
-- 2. SEDES Y CUERPO MÉDICO (NIVELES 1 Y 2)
-- ============================================================================

-- 2.1 CLINICAS (Depende de UBICACIONES)
CREATE TABLE CLINICAS (
    ID_CLINICA           NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    NOMBRE_CLINICA       VARCHAR2(100)  NOT NULL,
    ID_UBICACION         NUMBER         NOT NULL,
    DIRECCION            VARCHAR2(200),
    TELEFONO             VARCHAR2(20),
    FECHA_APERTURA       DATE,
    ESTADO               VARCHAR2(10)   DEFAULT 'ACTIVA' NOT NULL,
    CONSTRAINT PK_CLINICAS         PRIMARY KEY (ID_CLINICA),
    CONSTRAINT FK_CLINICAS_UBIC    FOREIGN KEY (ID_UBICACION) REFERENCES UBICACIONES (ID_UBICACION),
    CONSTRAINT CK_CLINICAS_ESTADO  CHECK (ESTADO IN ('ACTIVA','INACTIVA'))
);
COMMENT ON TABLE CLINICAS IS 'Sedes físicas que integran la red médica';

-- 2.2 MEDICOS (Depende de CLINICAS)
CREATE TABLE MEDICOS (
    ID_MEDICO               NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    NOMBRES                 VARCHAR2(60)   NOT NULL,
    APELLIDOS               VARCHAR2(60)   NOT NULL,
    ID_CLINICA_BASE         NUMBER         NOT NULL,
    NUM_COLEGIADO           VARCHAR2(20)   NOT NULL,
    FECHA_INGRESO           DATE           DEFAULT SYSDATE NOT NULL,
    ESTADO                  VARCHAR2(10)   DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_MEDICOS           PRIMARY KEY (ID_MEDICO),
    CONSTRAINT UQ_MEDICOS_COLEGIADO UNIQUE (NUM_COLEGIADO),
    CONSTRAINT FK_MEDICOS_CLINICA   FOREIGN KEY (ID_CLINICA_BASE) REFERENCES CLINICAS (ID_CLINICA),
    CONSTRAINT CK_MEDICOS_ESTADO    CHECK (ESTADO IN ('ACTIVO','INACTIVO'))
);
COMMENT ON TABLE MEDICOS IS 'Médicos adscritos a la red de clínicas';

-- 2.3 PACIENTES (Depende de UBICACIONES, CLINICAS, EMPRESAS, ASEGURADORAS)
CREATE TABLE PACIENTES (
    ID_PACIENTE                 NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    NOMBRES                     VARCHAR2(60)   NOT NULL,
    APELLIDOS                   VARCHAR2(60)   NOT NULL,
    FECHA_NACIMIENTO            DATE           NOT NULL,
    SEXO                        CHAR(1)        NOT NULL,
    ID_UBICACION                NUMBER         NOT NULL,
    DIRECCION                   VARCHAR2(200),
    ID_CLINICA_HABITUAL         NUMBER         NOT NULL,
    ID_EMPRESA                  NUMBER,
    ID_ASEGURADORA              NUMBER,
    NUMERO_POLIZA               VARCHAR2(40),
    FECHA_REGISTRO              DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_PACIENTES             PRIMARY KEY (ID_PACIENTE),
    CONSTRAINT FK_PACIENTES_UBIC        FOREIGN KEY (ID_UBICACION) REFERENCES UBICACIONES (ID_UBICACION),
    CONSTRAINT FK_PACIENTES_CLINICA     FOREIGN KEY (ID_CLINICA_HABITUAL) REFERENCES CLINICAS (ID_CLINICA),
    CONSTRAINT FK_PACIENTES_EMPRESA     FOREIGN KEY (ID_EMPRESA) REFERENCES EMPRESAS (ID_EMPRESA),
    CONSTRAINT FK_PACIENTES_ASEGURADORA FOREIGN KEY (ID_ASEGURADORA) REFERENCES ASEGURADORAS (ID_ASEGURADORA),
    CONSTRAINT CK_PACIENTES_SEXO        CHECK (SEXO IN ('M','F'))
);
COMMENT ON TABLE PACIENTES IS 'Registro maestro de expedientes de pacientes';

-- 2.4 MEDICOS_ESPECIALIDADES (Depende de MEDICOS, ESPECIALIDADES)
CREATE TABLE MEDICOS_ESPECIALIDADES (
    ID_MEDICO_ESPECIALIDAD  NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ID_MEDICO               NUMBER         NOT NULL,
    ID_ESPECIALIDAD         NUMBER         NOT NULL,
    NUM_REGISTRO_ESPECIAL   VARCHAR2(30),
    ES_PRINCIPAL            CHAR(1)        DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_MEDICOS_ESPEC        PRIMARY KEY (ID_MEDICO_ESPECIALIDAD),
    CONSTRAINT FK_MEDESP_MEDICO        FOREIGN KEY (ID_MEDICO) REFERENCES MEDICOS (ID_MEDICO),
    CONSTRAINT FK_MEDESP_ESPECIALIDAD  FOREIGN KEY (ID_ESPECIALIDAD) REFERENCES ESPECIALIDADES (ID_ESPECIALIDAD),
    CONSTRAINT UQ_MEDESP_MED_ESP       UNIQUE (ID_MEDICO, ID_ESPECIALIDAD),
    CONSTRAINT CK_MEDESP_PRINCIPAL     CHECK (ES_PRINCIPAL IN ('S','N'))
);
COMMENT ON TABLE MEDICOS_ESPECIALIDADES IS 'Especialidades acreditadas por cada profesional médico';

-- ============================================================================
-- 3. EXPEDIENTE TRANSACCIONAL DE CONSULTAS (NIVELES 3 Y 4)
-- ============================================================================

-- 3.1 CONSULTAS
CREATE TABLE CONSULTAS (
    ID_CONSULTA               NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ID_PACIENTE               NUMBER         NOT NULL,
    ID_CLINICA                NUMBER         NOT NULL,
    ID_MEDICO                 NUMBER         NOT NULL,
    ID_ESPECIALIDAD           NUMBER         NOT NULL,
    ID_TIPO_CONSULTA          NUMBER         NOT NULL,
    FECHA_CONSULTA            DATE           DEFAULT SYSDATE NOT NULL,
    PRECIO_CONSULTA           NUMBER(10,2)   NOT NULL,
    MOTIVO_CONSULTA           VARCHAR2(400)  NOT NULL,
    PRESCRIPCION              VARCHAR2(1000),
    CONSTRAINT PK_CONSULTAS             PRIMARY KEY (ID_CONSULTA),
    CONSTRAINT FK_CONSULTAS_PACIENTE    FOREIGN KEY (ID_PACIENTE) REFERENCES PACIENTES (ID_PACIENTE),
    CONSTRAINT FK_CONSULTAS_CLINICA     FOREIGN KEY (ID_CLINICA) REFERENCES CLINICAS (ID_CLINICA),
    CONSTRAINT FK_CONSULTAS_MEDICO      FOREIGN KEY (ID_MEDICO) REFERENCES MEDICOS (ID_MEDICO),
    CONSTRAINT FK_CONSULTAS_ESPEC       FOREIGN KEY (ID_ESPECIALIDAD) REFERENCES ESPECIALIDADES (ID_ESPECIALIDAD),
    CONSTRAINT FK_CONSULTAS_TIPO        FOREIGN KEY (ID_TIPO_CONSULTA) REFERENCES TIPOS_CONSULTA (ID_TIPO_CONSULTA),
    CONSTRAINT CK_CONSULTAS_PRECIO      CHECK (PRECIO_CONSULTA >= 0)
