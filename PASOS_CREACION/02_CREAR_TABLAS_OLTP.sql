CREATE OR REPLACE TRIGGER TRG_PACIENTES_VAL_FECHA_NAC
BEFORE INSERT OR UPDATE OF FECHA_NACIMIENTO ON PACIENTES
FOR EACH ROW
BEGIN
    IF :NEW.FECHA_NACIMIENTO > SYSDATE THEN
        RAISE_APPLICATION_ERROR(-20001, 'La fecha de nacimiento no puede ser una fecha futura.');
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_ACTUALIZA_SALDOS_PAGO
AFTER INSERT ON TRANSACCIONES_PAGO
FOR EACH ROW
DECLARE
    v_id_cobro NUMBER;
BEGIN
    -- 1. Actualizar el monto pagado y estado en la distribución
    UPDATE DISTRIBUCION_COBRO
    SET MONTO_PAGADO = MONTO_PAGADO + :NEW.MONTO_TRANSACCION,
        ESTADO = CASE 
            WHEN (MONTO_PAGADO + :NEW.MONTO_TRANSACCION) >= MONTO_ASIGNADO THEN 'PAGADO'
            ELSE 'PARCIAL'
        END
    WHERE ID_DISTRIBUCION = :NEW.ID_DISTRIBUCION
    RETURNING ID_COBRO INTO v_id_cobro;

    -- 2. Actualizar el cobro general de la consulta
    UPDATE COBROS_CONSULTA
    SET MONTO_TOTAL_PAGADO = MONTO_TOTAL_PAGADO + :NEW.MONTO_TRANSACCION,
        ESTADO_COBRO = CASE 
            WHEN (MONTO_TOTAL_PAGADO + :NEW.MONTO_TRANSACCION) >= MONTO_TOTAL_FACTURADO THEN 'PAGADO'
            ELSE 'PARCIAL'
        END
    WHERE ID_COBRO = v_id_cobro;
END;
/


