COMMENT ON TABLE CONSULTAS IS 'Registro principal de atención médica presencial';

-- 3.2 DIAGNOSTICOS
CREATE TABLE DIAGNOSTICOS (
    ID_DIAGNOSTICO         NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ID_CONSULTA            NUMBER        NOT NULL,
    ID_ENFERMEDAD          NUMBER        NOT NULL,
    FECHA_DIAGNOSTICO      DATE          DEFAULT SYSDATE NOT NULL,
    OBSERVACIONES          VARCHAR2(300),
    CONSTRAINT PK_DIAGNOSTICOS         PRIMARY KEY (ID_DIAGNOSTICO),
    CONSTRAINT FK_DIAGNOSTICOS_CONS    FOREIGN KEY (ID_CONSULTA) REFERENCES CONSULTAS (ID_CONSULTA),
    CONSTRAINT FK_DIAGNOSTICOS_ENFERM  FOREIGN KEY (ID_ENFERMEDAD) REFERENCES ENFERMEDADES (ID_ENFERMEDAD)
);
COMMENT ON TABLE DIAGNOSTICOS IS 'Cuadros clínicos y patologías identificadas en la consulta';

-- 3.3 CONSULTAS_PROCEDIMIENTOS
CREATE TABLE CONSULTAS_PROCEDIMIENTOS (
    ID_CONSULTA_PROCEDIMIENTO NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ID_CONSULTA               NUMBER        NOT NULL,
    ID_PROCEDIMIENTO          NUMBER        NOT NULL,
    CANTIDAD                  NUMBER(3)     DEFAULT 1 NOT NULL,
    PRECIO_UNITARIO           NUMBER(10,2)  NOT NULL,
    SUBTOTAL                  NUMBER(10,2)  GENERATED ALWAYS AS (CANTIDAD * PRECIO_UNITARIO) VIRTUAL,
    OBSERVACIONES             VARCHAR2(300),
    FECHA_REALIZACION         DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_CONSULTAS_PROCEDIMIENTOS PRIMARY KEY (ID_CONSULTA_PROCEDIMIENTO),
    CONSTRAINT FK_CONSPROC_CONSULTA        FOREIGN KEY (ID_CONSULTA) REFERENCES CONSULTAS (ID_CONSULTA),
    CONSTRAINT FK_CONSPROC_PROCEDIMIENTO   FOREIGN KEY (ID_PROCEDIMIENTO) REFERENCES PROCEDIMIENTOS (ID_PROCEDIMIENTO),
    CONSTRAINT CK_CONSPROC_CANTIDAD        CHECK (CANTIDAD > 0),
    CONSTRAINT CK_CONSPROC_PRECIO          CHECK (PRECIO_UNITARIO >= 0)
);
COMMENT ON TABLE CONSULTAS_PROCEDIMIENTOS IS 'Intervenciones clínicas ejecutadas durante la consulta';

-- ============================================================================
-- 4. FACTURACIÓN, COBERTURAS Y PAGOS (NIVELES 4, 5 Y 6)
-- ============================================================================

-- 4.1 COBROS_CONSULTA
CREATE TABLE COBROS_CONSULTA (
    ID_COBRO                  NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ID_CONSULTA               NUMBER        NOT NULL,
    MONTO_TOTAL_FACTURADO     NUMBER(10,2)  NOT NULL,
    MONTO_TOTAL_PAGADO        NUMBER(10,2)  DEFAULT 0 NOT NULL,
    SALDO_PENDIENTE           NUMBER(10,2)  GENERATED ALWAYS AS (MONTO_TOTAL_FACTURADO - MONTO_TOTAL_PAGADO) VIRTUAL,
    ESTADO_COBRO              VARCHAR2(15)  DEFAULT 'PENDIENTE' NOT NULL,
    FECHA_EMISION             DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_COBROS_CONSULTA     PRIMARY KEY (ID_COBRO),
    CONSTRAINT FK_COBROS_CONSULTA     FOREIGN KEY (ID_CONSULTA) REFERENCES CONSULTAS (ID_CONSULTA),
    CONSTRAINT UQ_COBROS_CONSULTA     UNIQUE (ID_CONSULTA),
    CONSTRAINT CK_COBROS_ESTADO       CHECK (ESTADO_COBRO IN ('PENDIENTE','PARCIAL','PAGADO','ANULADO')),
    CONSTRAINT CK_COBROS_MONTOS       CHECK (MONTO_TOTAL_FACTURADO >= 0 AND MONTO_TOTAL_PAGADO >= 0)
);
COMMENT ON TABLE COBROS_CONSULTA IS 'Cuenta global que consolida el precio de consulta y procedimientos';

-- 4.2 DISTRIBUCION_COBRO
CREATE TABLE DISTRIBUCION_COBRO (
    ID_DISTRIBUCION           NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ID_COBRO                  NUMBER        NOT NULL,
    TIPO_PAGADOR              VARCHAR2(20)  NOT NULL,
    ID_PACIENTE               NUMBER,
    ID_ASEGURADORA            NUMBER,
    ID_EMPRESA                NUMBER,
    PORCENTAJE                NUMBER(5,2)   NOT NULL,
    MONTO_ASIGNADO            NUMBER(10,2)  NOT NULL,
    MONTO_PAGADO              NUMBER(10,2)  DEFAULT 0 NOT NULL,
    SALDO_PENDIENTE           NUMBER(10,2)  GENERATED ALWAYS AS (MONTO_ASIGNADO - MONTO_PAGADO) VIRTUAL,
    ESTADO                    VARCHAR2(15)  DEFAULT 'PENDIENTE' NOT NULL,
    CONSTRAINT PK_DISTRIBUCION_COBRO  PRIMARY KEY (ID_DISTRIBUCION),
    CONSTRAINT FK_DISTCOB_COBRO       FOREIGN KEY (ID_COBRO) REFERENCES COBROS_CONSULTA (ID_COBRO),
    CONSTRAINT FK_DISTCOB_PACIENTE    FOREIGN KEY (ID_PACIENTE) REFERENCES PACIENTES (ID_PACIENTE),
    CONSTRAINT FK_DISTCOB_ASEGURADORA FOREIGN KEY (ID_ASEGURADORA) REFERENCES ASEGURADORAS (ID_ASEGURADORA),
    CONSTRAINT FK_DISTCOB_EMPRESA     FOREIGN KEY (ID_EMPRESA) REFERENCES EMPRESAS (ID_EMPRESA),
    CONSTRAINT CK_DISTCOB_TIPO        CHECK (TIPO_PAGADOR IN ('PACIENTE','ASEGURADORA','EMPRESA')),
    CONSTRAINT CK_DISTCOB_PORCENTAJE  CHECK (PORCENTAJE > 0 AND PORCENTAJE <= 100),
    CONSTRAINT CK_DISTCOB_MONTOS      CHECK (MONTO_ASIGNADO >= 0 AND MONTO_PAGADO >= 0),
    CONSTRAINT CK_DISTCOB_ESTADO      CHECK (ESTADO IN ('PENDIENTE','PARCIAL','PAGADO','ANULADO')),
    CONSTRAINT CK_DISTCOB_PAGADOR_COH CHECK (
        (TIPO_PAGADOR = 'PACIENTE'    AND ID_PACIENTE IS NOT NULL AND ID_ASEGURADORA IS NULL AND ID_EMPRESA IS NULL) OR
        (TIPO_PAGADOR = 'ASEGURADORA' AND ID_ASEGURADORA IS NOT NULL AND ID_PACIENTE IS NULL AND ID_EMPRESA IS NULL) OR
        (TIPO_PAGADOR = 'EMPRESA'     AND ID_EMPRESA IS NOT NULL AND ID_PACIENTE IS NULL AND ID_ASEGURADORA IS NULL)
    )
);
COMMENT ON TABLE DISTRIBUCION_COBRO IS 'Reparto de responsabilidad económica por pagador';

-- 4.3 TRANSACCIONES_PAGO
CREATE TABLE TRANSACCIONES_PAGO (
    ID_TRANSACCION            NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ID_DISTRIBUCION           NUMBER        NOT NULL,
    ID_FORMA_PAGO             NUMBER        NOT NULL,
    MONTO_TRANSACCION         NUMBER(10,2)  NOT NULL,
    FECHA_PAGO                DATE          DEFAULT SYSDATE NOT NULL,
    NUMERO_REFERENCIA         VARCHAR2(50),
    OBSERVACIONES             VARCHAR2(250),
    CONSTRAINT PK_TRANSACCIONES_PAGO  PRIMARY KEY (ID_TRANSACCION),
    CONSTRAINT FK_TRANSPAGO_DISTRIB   FOREIGN KEY (ID_DISTRIBUCION) REFERENCES DISTRIBUCION_COBRO (ID_DISTRIBUCION),
    CONSTRAINT FK_TRANSPAGO_FORMAPAGO FOREIGN KEY (ID_FORMA_PAGO) REFERENCES FORMAS_PAGO (ID_FORMA_PAGO),
    CONSTRAINT CK_TRANSPAGO_MONTO     CHECK (MONTO_TRANSACCION > 0)
);
COMMENT ON TABLE TRANSACCIONES_PAGO IS 'Historial inmutable de abonos recibidos en caja o por transferencia';

