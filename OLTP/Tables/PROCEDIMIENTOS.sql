CREATE TABLE PROCEDIMIENTOS (
    ID_PROCEDIMIENTO       NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    CODIGO_PROCEDIMIENTO   VARCHAR2(20),
    NOMBRE_PROCEDIMIENTO   VARCHAR2(120)  NOT NULL,
    DESCRIPCION            VARCHAR2(300),
    COSTO_BASE             NUMBER(10,2)   DEFAULT 0 NOT NULL,
    ESTADO                 VARCHAR2(10)   DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_PROCEDIMIENTOS        PRIMARY KEY (ID_PROCEDIMIENTO),
    CONSTRAINT UQ_PROCEDIMIENTOS_COD    UNIQUE (CODIGO_PROCEDIMIENTO),
    CONSTRAINT CK_PROCEDIMIENTOS_COSTO  CHECK (COSTO_BASE >= 0),
    CONSTRAINT CK_PROCEDIMIENTOS_ESTADO CHECK (ESTADO IN ('ACTIVO','INACTIVO'))
);

COMMENT ON TABLE PROCEDIMIENTOS IS 'Catálogo de intervenciones, terapias y procedimientos clínicos';

GRANT SELECT ON PROCEDIMIENTOS TO stg_clinica_user, dwh_clinica_user;
