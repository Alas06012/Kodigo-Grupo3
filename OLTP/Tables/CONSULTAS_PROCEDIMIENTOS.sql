CREATE TABLE CONSULTAS_PROCEDIMIENTOS (
    ID_CONSULTA_PROCEDIMIENTO NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ID_CONSULTA               NUMBER        NOT NULL,
    ID_PROCEDIMIENTO          NUMBER        NOT NULL,
    CANTIDAD                  NUMBER(3)     DEFAULT 1 NOT NULL,
    PRECIO_UNITARIO           NUMBER(10,2)  NOT NULL,
    SUBTOTAL                  NUMBER(10,2)  GENERATED ALWAYS AS (CANTIDAD * PRECIO_UNITARIO) VIRTUAL,
    OBSERVACIONES             VARCHAR2(300),
    FECHA_REALIZACION         DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_CONSULTAS_PROC          PRIMARY KEY (ID_CONSULTA_PROCEDIMIENTO),
    CONSTRAINT FK_CONSPROC_CONSULTA       FOREIGN KEY (ID_CONSULTA) REFERENCES CONSULTAS (ID_CONSULTA),
    CONSTRAINT FK_CONSPROC_PROCEDIMIENTO  FOREIGN KEY (ID_PROCEDIMIENTO) REFERENCES PROCEDIMIENTOS (ID_PROCEDIMIENTO),
    CONSTRAINT CK_CONSPROC_CANTIDAD       CHECK (CANTIDAD > 0),
    CONSTRAINT CK_CONSPROC_PRECIO         CHECK (PRECIO_UNITARIO >= 0)
);

COMMENT ON TABLE CONSULTAS_PROCEDIMIENTOS IS 'Procedimientos aplicados al paciente durante la consulta (subtotal virtual)';

GRANT SELECT ON CONSULTAS_PROCEDIMIENTOS TO stg_clinica_user, dwh_clinica_user;
