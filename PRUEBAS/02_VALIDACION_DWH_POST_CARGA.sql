PROMPT 1. RESUMEN EJECUTIVO DEL ÚLTIMO LOTE EJECUTADO EN CTL_ETL_AUDIT
PROMPT ============================================================================

SELECT 
    BATCH_ID,
    COUNT(*) AS TOTAL_PROCESOS,
    SUM(CASE WHEN ESTADO = 'SUCCESS' THEN 1 ELSE 0 END) AS EXITOSOS,
    SUM(CASE WHEN ESTADO = 'FAILED'  THEN 1 ELSE 0 END) AS FALLIDOS,
    SUM(FILAS_LEIDAS) AS TOTAL_LEIDAS,
    SUM(FILAS_INSERTADAS) AS TOTAL_INSERTADAS,
    SUM(FILAS_ACTUALIZADAS) AS TOTAL_ACTUALIZADAS,
    ROUND(SUM(DURACION_SEGUNDOS), 2) AS SEGUNDOS_TOTALES,
    TO_CHAR(MIN(FECHA_INICIO), 'YYYY-MM-DD HH24:MI:SS') AS INICIO,
    TO_CHAR(MAX(FECHA_FIN),    'YYYY-MM-DD HH24:MI:SS') AS FIN
FROM CTL_ETL_AUDIT
WHERE BATCH_ID = (SELECT MAX(BATCH_ID) FROM CTL_ETL_AUDIT)
GROUP BY BATCH_ID;

