PROMPT [4.2] Prorrateo Financiero en FACT_CONSULTA_DIAGNOSTICOS (Sin Doble Conteo):
SELECT 
    fd.BK_ID_CONSULTA,
    e.NOMBRE_ENFERMEDAD,
    e.CODIGO_CIE10,
    fd.TOTAL_DIAGNOSTICOS_CONS AS TOTAL_DIAGS,
    fd.MONTO_TOTAL_CONSULTA AS MTO_TOTAL,
    fd.MONTO_PRORRATEADO AS MTO_PRORRATEADO
FROM FACT_CONSULTA_DIAGNOSTICOS fd
JOIN DIM_ENFERMEDAD e ON fd.SK_ENFERMEDAD = e.SK_ENFERMEDAD
JOIN FACT_CONSULTAS f ON fd.SK_CONSULTA = f.SK_CONSULTA
JOIN DIM_TIEMPO t ON f.SK_TIEMPO = t.SK_TIEMPO
WHERE t.FECHA >= TRUNC(SYSDATE) - 3
ORDER BY fd.BK_ID_CONSULTA DESC, fd.BK_ID_DIAGNOSTICO ASC;

