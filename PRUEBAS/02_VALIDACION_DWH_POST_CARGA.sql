FROM CTL_ETL_AUDIT
WHERE BATCH_ID = (SELECT MAX(BATCH_ID) FROM CTL_ETL_AUDIT)
  AND (FILAS_INSERTADAS > 0 OR FILAS_ACTUALIZADAS > 0)
