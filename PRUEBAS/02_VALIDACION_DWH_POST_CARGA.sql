PROMPT [4.1] Consultas Recientes en FACT_CONSULTAS (Ventana Lookback de Prueba):
SELECT 
    f.BK_ID_CONSULTA,
    t.FECHA,
    p.NOMBRE_COMPLETO AS PACIENTE,
    m.NOMBRE_COMPLETO AS MEDICO,
    c.NOMBRE_CLINICA AS CLINICA,
    tc.NOMBRE_TIPO AS TIPO_CONSULTA,
    f.CANTIDAD_PROCEDIMIENTOS AS PROCS,
    f.PRECIO_HONORARIOS AS MTO_CONS,
    f.TOTAL_PROCEDIMIENTOS AS MTO_PROC,
    f.MONTO_TOTAL_FACTURADO AS TOTAL_FACT,
    f.MONTO_TOTAL_PAGADO AS TOTAL_PAGADO,
    f.SALDO_PENDIENTE AS SALDO,
    f.ESTADO_COBRO
FROM FACT_CONSULTAS f
JOIN DIM_TIEMPO t ON f.SK_TIEMPO = t.SK_TIEMPO
JOIN DIM_PACIENTE p ON f.SK_PACIENTE = p.SK_PACIENTE
JOIN DIM_MEDICO m ON f.SK_MEDICO = m.SK_MEDICO
JOIN DIM_CLINICA c ON f.SK_CLINICA = c.SK_CLINICA
JOIN DIM_TIPO_CONSULTA tc ON f.SK_TIPO_CONSULTA = tc.SK_TIPO_CONSULTA
WHERE t.FECHA >= TRUNC(SYSDATE) - 3
ORDER BY f.BK_ID_CONSULTA DESC;

