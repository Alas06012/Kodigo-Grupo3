PROMPT [4.3] Detalle Económico por Pagador en FACT_COBROS_DISTRIBUCION:
SELECT 
    fcd.BK_ID_CONSULTA,
    fcd.TIPO_PAGADOR,
    p.NOMBRE_PAGADOR,
    fp.NOMBRE_FORMA_PAGO AS FORMA_PAGO_PREDOMINANTE,
    fcd.PORCENTAJE_COBERTURA AS PORCENTAJE,
    fcd.MONTO_ASIGNADO,
    fcd.MONTO_PAGADO,
    fcd.SALDO_PENDIENTE,
    fcd.ESTADO_DISTRIBUCION
FROM FACT_COBROS_DISTRIBUCION fcd
LEFT JOIN DIM_PAGADOR p ON fcd.SK_PAGADOR = p.SK_PAGADOR
LEFT JOIN DIM_FORMA_PAGO fp ON fcd.SK_FORMA_PAGO_PREDOMINANTE = fp.SK_FORMA_PAGO
JOIN FACT_CONSULTAS f ON fcd.BK_ID_CONSULTA = f.BK_ID_CONSULTA
JOIN DIM_TIEMPO t ON f.SK_TIEMPO = t.SK_TIEMPO
WHERE t.FECHA >= TRUNC(SYSDATE) - 3
ORDER BY fcd.BK_ID_CONSULTA DESC, fcd.BK_ID_DISTRIBUCION ASC;

